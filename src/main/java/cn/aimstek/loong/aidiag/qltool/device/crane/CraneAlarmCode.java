    /**
     * 按位号取报警名称。
     *
     * @param code 报警位号
     * @return 报警中文名称；未定义位返回 {@code null}
     */
    public static String name(int code) {
        if (code < 0 || code >= NAMES.length) {
            return null;
        }
        return NAMES[code];
    }

    /**
     * 按位号取展示文本，未定义位回退为"报警位:N"。
     *
     * @param code 报警位号
     * @return 用于界面展示的报警描述
     */
    public static String display(int code) {
        String name = name(code);
        return name != null ? name : "报警位:" + code;
    }
